import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sdkRoot = join(here, '..');
const lockPath = join(sdkRoot, 'foundation.lock.json');

const TS_TARGET = join(sdkRoot, 'src', 'foundation', 'brand.generated.ts');

const PICKS = [
  { path: ['brand', 'primary'], from: ['colorsLight', 'brand', 'primary'], css: '--color-brand-primary', note: 'burgundy/600' },
  { path: ['brand', 'secondary'], from: ['colorsLight', 'brand', 'secondary'], css: '--color-brand-secondary', note: 'orange/500' },
  { path: ['palette', 'burgundy', '700'], from: ['palette', 'burgundy', '700'], css: '--color-brand-primary-hover', note: 'hover shade for brand.primary' },
  { path: ['palette', 'base', 'white'], from: ['palette', 'base', 'white'], css: '--color-base-white', note: '' },
  { path: ['text', 'primaryInverse'], from: ['colorsLight', 'text', 'primaryInverse'], css: '--color-text-primary-inverse', note: 'text on brand.primary' },
];

const MODE_INVARIANT = [['brand', 'primary'], ['brand', 'secondary'], ['text', 'primaryInverse']];

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--tag' || arg === '--from') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) fail(`${arg} needs a value`);
      out[arg.slice(2)] = value;
      i += 1;
    } else {
      fail(`unknown argument ${arg}`);
    }
  }
  return out;
}

function fail(message) {
  console.error(`[sync-foundation] ${message}`);
  process.exit(1);
}

function readLock() {
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'));
  for (const key of ['repo', 'tag', 'source']) {
    if (typeof lock[key] !== 'string' || lock[key] === '') fail(`foundation.lock.json is missing "${key}"`);
  }
  return lock;
}

function fetchSource(lock, from) {
  if (from !== undefined) {
    const path = resolve(process.cwd(), from);
    console.log(`[sync-foundation] reading ${path}`);
    return readFileSync(path, 'utf8');
  }
  const endpoint = `repos/${lock.repo}/contents/${lock.source}?ref=${lock.tag}`;
  console.log(`[sync-foundation] gh api ${endpoint}`);
  const encoded = execFileSync('gh', ['api', endpoint, '--jq', '.content'], { encoding: 'utf8' });
  return Buffer.from(encoded, 'base64').toString('utf8');
}

async function evaluateModule(source) {
  const ts = createRequire(import.meta.url)('typescript');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 },
  });
  const dir = mkdtempSync(join(tmpdir(), 'maytes-foundation-'));
  const file = join(dir, 'tokens.mjs');
  try {
    writeFileSync(file, outputText);
    return await import(pathToFileURL(file).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function dig(root, path) {
  let node = root;
  for (const key of path) {
    if (node === null || typeof node !== 'object' || !(key in node)) return undefined;
    node = node[key];
  }
  return node;
}

function assertHex(value, path) {
  if (typeof value !== 'string' || !/^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$/.test(value)) {
    fail(`${path.join('.')} is not a hex colour in the tokens module: ${JSON.stringify(value)}`);
  }
  return value.toUpperCase();
}

function set(root, path, value) {
  let node = root;
  for (const key of path.slice(0, -1)) {
    if (!(key in node)) node[key] = {};
    node = node[key];
  }
  node[path[path.length - 1]] = value;
}

function checkModeInvariance(tokens) {
  for (const path of MODE_INVARIANT) {
    const light = dig(tokens.colorsLight, path);
    const dark = dig(tokens.colorsDark, path);
    if (light !== dark) {
      console.warn(`[sync-foundation] warning: ${path.join('.')} differs between light (${light}) and dark (${dark}); the light value is vendored`);
    }
  }
}

function keyLiteral(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : /^\d+$/.test(key) ? key : JSON.stringify(key);
}

function renderObject(node, indent) {
  const pad = '  '.repeat(indent);
  const lines = Object.entries(node).map(([key, value]) => {
    const rendered = typeof value === 'string' ? `'${value}'` : renderObject(value, indent + 1);
    return `${pad}  ${keyLiteral(key)}: ${rendered},`;
  });
  return `{\n${lines.join('\n')}\n${pad}}`;
}

function header(lock, comment) {
  return `${comment[0]} GENERATED by scripts/sync-foundation-tokens.mjs from ${lock.repo} ${lock.tag} ${lock.source} — DO NOT EDIT. Refresh: npm run sync:foundation -- --tag vX.Y.Z${comment[1]}\n`;
}

function renderTs(lock, foundation) {
  const notes = PICKS.map((p) => `//   ${p.path.join('.')} <- ${p.from.join('.')}${p.note ? ` (${p.note})` : ''}`).join('\n');
  return [
    header(lock, ['//', '']),
    `// Subset of the foundation used by the checkout button:`,
    notes,
    '',
    `export const FOUNDATION_TAG = '${lock.tag}';`,
    '',
    `export const foundation = ${renderObject(foundation, 0)} as const;`,
    '',
  ].join('\n');
}

function writeOut(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch { current = ''; }
  if (current === content) {
    console.log(`[sync-foundation] unchanged ${path}`);
    return;
  }
  writeFileSync(path, content);
  console.log(`[sync-foundation] wrote ${path}`);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const lock = readLock();
  if (args.tag !== undefined) lock.tag = args.tag;
  if (!/^v\d+\.\d+\.\d+$/.test(lock.tag)) fail(`tag must look like vX.Y.Z, got ${lock.tag}`);

  const tokens = await evaluateModule(fetchSource(lock, args.from));
  for (const name of ['palette', 'colorsLight', 'colorsDark']) {
    if (typeof tokens[name] !== 'object' || tokens[name] === null) fail(`tokens module has no "${name}" export`);
  }
  checkModeInvariance(tokens);

  const foundation = {};
  for (const pick of PICKS) set(foundation, pick.path, assertHex(dig(tokens, pick.from), pick.from));

  writeOut(TS_TARGET, renderTs(lock, foundation));
  writeOut(lockPath, `${JSON.stringify({ repo: lock.repo, tag: lock.tag, source: lock.source }, null, 2)}\n`);
  console.log(`[sync-foundation] pinned to ${lock.repo} ${lock.tag}`);
}

main().catch((err) => fail(err instanceof Error ? err.message : String(err)));
